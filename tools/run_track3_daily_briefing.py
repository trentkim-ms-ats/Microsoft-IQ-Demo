"""Run WebIQ live and write a review-ready Track3 briefing."""

import argparse
import json
import os
import sys
from datetime import datetime, timezone
from functools import partial
from pathlib import Path

from tools import live_demo, webiq
from tools.azure_demo_auth import require_separate_identity


def configure_deployment(args):
    selected = (args.resource_group, args.account, args.deployment)
    if args.provisioned_config is not None:
        if any(selected) or args.subscription:
            raise ValueError("--provisioned-config cannot be combined with explicit resource arguments.")
        config = json.loads(args.provisioned_config.read_text(encoding="utf-8"))
        fields = {
            "subscription": "AZURE_OPENAI_SUBSCRIPTION", "resourceGroup": "AZURE_RESOURCE_GROUP",
            "account": "AZURE_AI_ACCOUNT_NAME", "deployment": "AZURE_OPENAI_MODEL",
            "endpoint": "AZURE_OPENAI_ENDPOINT",
        }
        if not isinstance(config, dict) or any(
            not isinstance(config.get(key), str) or not config[key].strip() for key in fields
        ):
            raise ValueError("The provisioned config must specify a subscription, group, account, deployment, and endpoint.")
        os.environ.update({env: config[key] for key, env in fields.items()})
        return
    if not any(selected):
        return
    if not all(selected):
        raise ValueError("Provide --resource-group, --account and --deployment together.")
    if not args.subscription:
        raise ValueError("Use --subscription with resource discovery in the separate Azure tenant.")
    os.environ["AZURE_OPENAI_MODEL"] = args.deployment
    os.environ["AZURE_RESOURCE_GROUP"] = args.resource_group
    os.environ["AZURE_AI_ACCOUNT_NAME"] = args.account


def respond_with_budget(respond, body):
    return respond(body | {"max_output_tokens": 10_000})


def run(profile, specs, model, respond, now):
    results = [live_demo.collect_web_evidence(scenario, spec, model, respond) for scenario, spec in specs.items()]
    return {
        "executionMode": "live",
        "profile": profile,
        "startedAt": now.isoformat(timespec="seconds"),
        "status": "succeeded" if all(r["status"] == "succeeded" for r in results) else "incomplete",
        "humanApprovalRequired": True,
        "scenarios": results,
    }


def save_report(report, output_dir, now):
    run_dir = output_dir / (now.strftime("%Y%m%dT%H%M%S%fZ") + "-" + report["profile"])
    run_dir.mkdir(mode=0o700, parents=True, exist_ok=False)
    (run_dir / "briefing.json").write_text(
        json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8",
    )
    lines = [
        "# Track 3 — WebIQ", "",
        f"Profile: `{report['profile']}` | Status: `{report['status']}` | UTC: {report['startedAt']}", "",
        "Live search results require review of the original sources before use. "
        "This file does not establish an internal cause or authorize actions.", "",
    ]
    if report.get("preflightError"):
        lines.extend([live_demo.markdown_literal(report["preflightError"]), ""])
        lines.extend(["Not run: " + ", ".join(report["plannedScenarios"]), ""])
    for row in report["scenarios"]:
        lines.extend([f"## {row['scenarioId']} — {row['topic']}", "", f"Status: `{row['status']}`", ""])
        if row["status"] == "succeeded":
            lines.extend([live_demo.markdown_literal(row["answer"]), "", f"Limit: {row['limitations']}", ""])
            for cite in row["citations"]:
                lines.extend([
                    live_demo.markdown_literal(f"{cite['id']}: {cite['title']}\n{cite['url']}\n{cite['observedAt']} | {cite['scope']}"),
                    "",
                ])
        else:
            lines.extend([live_demo.markdown_literal(row["error"]), ""])
    (run_dir / "briefing.md").write_text("\n".join(lines), encoding="utf-8")
    return run_dir


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--profile", choices=(*webiq.PROFILES, "all"), default="workshop")
    parser.add_argument("--scenario", choices=webiq.PROFILES["demo"], help="Run one scenario instead of the full profile.")
    parser.add_argument("--days", type=int, default=7, help="Workshop lookback in UTC days (1–90).")
    parser.add_argument("--check-config", action="store_true", help="Validate the local query contract only; no web or Azure calls.")
    parser.add_argument("--resource-group")
    parser.add_argument("--account", help="Existing Foundry account name.")
    parser.add_argument("--deployment", help="Existing Azure OpenAI deployment name.")
    parser.add_argument("--subscription", help="Azure subscription for deployment discovery and Entra authentication.")
    parser.add_argument("--provisioned-config", type=Path, help="Track 3 target generated by the Foundry provisioner.")
    parser.add_argument("--output-dir", type=Path, default=Path("outputs/track3"))
    args = parser.parse_args()
    try:
        now = datetime.now(timezone.utc)
        profiles = tuple(webiq.PROFILES) if args.profile == "all" else (args.profile,)
        if args.scenario:
            if args.profile == "all":
                parser.error("--scenario requires a single profile.")
            if args.scenario not in webiq.PROFILES[args.profile]:
                raise ValueError(f"{args.scenario} is not in the {args.profile} profile.")
        catalogs = {profile: webiq.load_specs(profile, now, args.days) for profile in profiles}
        if args.scenario:
            catalogs[args.profile] = {args.scenario: catalogs[args.profile][args.scenario]}
        if args.check_config:
            if args.profile == "all":
                result = {"mode": "config-check", "profiles": {name: list(specs) for name, specs in catalogs.items()}}
            else:
                result = {"mode": "config-check", "profile": args.profile, "scenarios": list(catalogs[args.profile])}
            print(json.dumps(result))
            return 0
        try:
            identity = require_separate_identity()
            configure_deployment(args)
            if args.subscription:
                os.environ["AZURE_OPENAI_SUBSCRIPTION"] = args.subscription
            if args.provisioned_config is not None:
                model, respond = live_demo.prepare_separate_foundry(
                    identity, allow_services_endpoint=True, rate_limit_wait=120,
                )
                respond = partial(respond_with_budget, respond)
            else:
                model, respond = live_demo.prepare_separate_foundry(identity, allow_services_endpoint=True)
        except (live_demo.LiveServiceError, OSError, ValueError) as error:
            preflight_error = str(error)
        else:
            preflight_error = None
        summaries = {}
        for profile, specs in catalogs.items():
            if preflight_error is None:
                report = run(profile, specs, model, respond, now)
            else:
                report = {
                    "executionMode": "live", "profile": profile, "status": "blocked",
                    "startedAt": now.isoformat(timespec="seconds"), "humanApprovalRequired": True,
                    "preflightError": preflight_error, "plannedScenarios": list(specs), "scenarios": [],
                }
            run_dir = save_report(report, args.output_dir, now)
            summaries[profile] = {
                "status": report["status"],
                "report": str(run_dir / "briefing.json"),
                "scenarios": {row["scenarioId"]: row["status"] for row in report["scenarios"]},
            }
        status = (
            "blocked" if preflight_error is not None else
            "succeeded" if all(row["status"] == "succeeded" for row in summaries.values()) else "incomplete"
        )
        result = {"status": status, "profiles": summaries} if args.profile == "all" else summaries[args.profile]
        print(json.dumps(result))
        return 0 if status == "succeeded" else 1
    except (live_demo.LiveServiceError, OSError, KeyError, ValueError) as error:
        print(f"Track 3 briefing failed: {error}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
